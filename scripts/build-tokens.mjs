// Writes src/styles/tokens.css from docs/design/figma-variables.json, the snapshot of the Figma Design
// System (D-14). Run `npm run tokens` after re-exporting the snapshot; tests/unit/tokens.test.ts fails
// when the two drift apart.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const SNAPSHOT = join(ROOT, "docs", "design", "figma-variables.json");
const OUT = join(ROOT, "src", "styles", "tokens.css");

// Figma frames are 390 / 834 / 1440. Tablet sizes start at the smallest iPad (iPad mini, 744 CSS px);
// desktop sizes start at 1280 px, the narrowest common laptop, so 1280–1439 px screens get desktop type.
export const TABLET_MIN = 744;
export const DESKTOP_MIN = 1280;

/** The CSS custom property (without "--") for a Figma variable, in Tailwind's namespaces where one fits. */
export function cssName(figmaName) {
  const [group, ...rest] = figmaName.split("/");
  const tail = rest.join("-");
  if (group === "size") return `text-${tail}`;
  if (group === "line") return `text-${tail}--line-height`;
  // Figma's named spacing stays out of Tailwind's --spacing-* namespace: names like "md" there would also
  // feed max-w-md, w-xs and size-lg. Use p-(--space-md), or Tailwind's numeric steps (4 px each).
  if (group === "spacing") return `space-${tail}`;
  if (group === "radius" || group === "layout") return `${group}-${tail}`;
  return `color-${figmaName.replaceAll("/", "-")}`;
}

/** WCAG 2 contrast ratio of two opaque #rrggbb colours (a translucent colour has no fixed ratio). */
export function contrastRatio(a, b) {
  const lum = (hex) => {
    if (!/^#[0-9a-f]{6}$/i.test(hex)) throw new Error(`contrastRatio needs an opaque #rrggbb colour, got ${hex}`);
    const [r, g, bl] = [1, 3, 5].map((i) => {
      const c = parseInt(hex.slice(i, i + 2), 16) / 255;
      return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
    });
    return 0.2126 * r + 0.7152 * g + 0.0722 * bl;
  };
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

const FALLBACK = { "Barlow Condensed": '"Arial Narrow", system-ui, sans-serif', Barlow: "system-ui, sans-serif" };
// next/font self-hosts each family and names it in a variable (--font-barlow, --font-barlow-condensed; see
// src/app/fonts.ts); the plain family name is the fallback when that variable is missing.
const fontVar = (family) => `--font-${family.toLowerCase().replaceAll(" ", "-")}`;
const font = (family) => `var(${fontVar(family)}, "${family}"), ${FALLBACK[family] ?? "sans-serif"}`;

/** Sizes that change between two breakpoints, as declarations. */
function sizeOverrides(sizes, from, to) {
  return Object.entries(sizes)
    .filter(([, v]) => v[to] !== v[from])
    .map(([name, v]) => `    --${cssName(name)}: ${v[to]}px;`);
}

function textStyleUtility(style, fonts) {
  const sized = typeof style.size === "string";
  const family = Object.keys(fonts).find((role) => fonts[role] === style.family);
  if (!family) throw new Error(`text style ${style.name} uses ${style.family}, which is not a font in the snapshot`);
  const lines = [
    `@utility type-${style.name} {`,
    `  font-family: var(--font-${family});`,
    `  font-size: ${sized ? `var(--text-${style.size})` : `${style.size}px`};`,
    `  line-height: ${sized ? `var(--text-${style.line}--line-height)` : `${style.line}px`};`,
    `  font-weight: ${style.weight};`,
  ];
  if (style.trackingPercent) lines.push(`  letter-spacing: ${Number((style.trackingPercent / 100).toFixed(4))}em;`);
  if (style.uppercase) lines.push("  text-transform: uppercase;");
  if (style.name.startsWith("number")) lines.push("  font-variant-numeric: tabular-nums;");
  return [...lines, "}"].join("\n");
}

/** The whole of tokens.css for a snapshot. */
export function buildTokensCss(figma) {
  // D-92: one text size per style at every width. The approved screens show Figma's Desktop typography on
  // phone and tablet too (their frames never switch the Typography mode), so type takes the Desktop value
  // everywhere; only the layout tokens change with the breakpoint.
  const typography = Object.fromEntries(
    Object.entries(figma.typography).map(([name, v]) => [name, { phone: v.desktop, tablet: v.desktop, desktop: v.desktop }]),
  );
  // layout/breakpoint only names Figma's frame widths; the CSS breakpoints are TABLET_MIN and DESKTOP_MIN.
  const sizes = Object.fromEntries(
    Object.entries({ ...figma.tokens, ...typography }).filter(([name]) => name !== "layout/breakpoint"),
  );
  const shadows = Object.entries(figma.effects).map(
    ([name, layers]) => `  --shadow-${name}: ${layers.map(([x, y, blur, spread, c]) => `${x}px ${y}px ${blur}px ${spread}px ${c}`).join(", ")};`,
  );
  return [
    "/* GENERATED by scripts/build-tokens.mjs from docs/design/figma-variables.json (the Figma Design System,",
    "   D-14). Do not edit by hand: re-export the snapshot from Figma, then run `npm run tokens`.",
    "   The only file in src/ allowed to hold colours (check-tokens). */",
    "",
    "/* Light or dark follows the device; a switch sets data-theme on <html> to override it (D-37). */",
    ":root {",
    "  color-scheme: light dark;",
    "}",
    ':root[data-theme="light"] {',
    "  color-scheme: light;",
    "}",
    ':root[data-theme="dark"] {',
    "  color-scheme: dark;",
    "}",
    "",
    "/* Phone values. Tailwind's own palette, sizes, radii and shadows are switched off so only these exist. */",
    "@theme static {",
    "  --color-*: initial;",
    "  --text-*: initial;",
    "  --radius-*: initial;",
    "  --shadow-*: initial;",
    "  --breakpoint-*: initial;",
    `  --breakpoint-tablet: ${TABLET_MIN}px;`,
    `  --breakpoint-desktop: ${DESKTOP_MIN}px;`,
    "",
    "  /* Colour · Theme: light-dark(light, dark) */",
    ...Object.entries(figma.theme).map(([name, v]) => `  --${cssName(name)}: light-dark(${v.light}, ${v.dark});`),
    "",
    `  --font-display: ${font(figma.fonts.display)};`,
    `  --font-text: ${font(figma.fonts.text)};`,
    "  --default-font-family: var(--font-text);",
    "",
    "  /* Tokens and Typography at phone (390) */",
    ...Object.entries(sizes).map(([name, v]) => `  --${cssName(name)}: ${v.phone}px;`),
    "",
    "  /* Elevation (Figma effect styles) */",
    ...shadows,
    "}",
    "",
    `/* Tablet (834 in Figma) from ${TABLET_MIN} px: only the values that differ from phone. */`,
    `@media (min-width: ${TABLET_MIN}px) {`,
    "  :root {",
    ...sizeOverrides(sizes, "phone", "tablet"),
    "  }",
    "}",
    "",
    `/* Desktop (1440 in Figma) from ${DESKTOP_MIN} px: only the values that differ from tablet. */`,
    `@media (min-width: ${DESKTOP_MIN}px) {`,
    "  :root {",
    ...sizeOverrides(sizes, "tablet", "desktop"),
    "  }",
    "}",
    "",
    "/* Touch screens keep the phone and tablet touch target at any width (an iPad Pro is 1366 px wide). */",
    "@media (pointer: coarse) {",
    "  :root {",
    `    --${cssName("layout/touch-target")}: ${sizes["layout/touch-target"].phone}px;`,
    "  }",
    "}",
    "",
    "/* Figma text styles, one class each: class=\"type-h1\". */",
    ...figma.textStyles.map((s) => textStyleUtility(s, figma.fonts) + "\n"),
  ].join("\n");
}

if (process.argv[1] === import.meta.filename) {
  writeFileSync(OUT, buildTokensCss(JSON.parse(readFileSync(SNAPSHOT, "utf8"))));
  console.log(`build-tokens: wrote ${OUT.slice(ROOT.length + 1)}`);
}
