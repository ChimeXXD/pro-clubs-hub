// Writes src/styles/motion.css: the motion tokens every animation uses (docs/design/motion-bookmarks.pdf, D-117).
// Springs are "stiffness damping" (mass 1), the presets the bookmarked DesignBookmark components share; each becomes
// a CSS linear() easing sampled from the spring's own curve, with the time it takes to settle as its duration, so CSS
// transitions and the Web Animations API can use them without a motion library. Run: node scripts/build-springs.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const SPRINGS = {
  follow: [900, 50], // held by the pointer: no overshoot, no lag
  settle: [280, 22], // letting go, landing on a value: one small overshoot
  soft: [260, 24], // larger moves: panels, sheets
  pop: [520, 16], // an icon or number on select
  fade: [420, 32], // opacity and small slides
  lead: [600, 30], // the leading edge of something that stretches (Rubber dock): quick, a little overshoot
  trail: [300, 30], // its trailing edge: later and softer, so the shape stretches, then snaps back
};

/** Position of a unit spring from 0 to 1 at time t (seconds). */
export function springAt([stiffness, damping], t) {
  const w0 = Math.sqrt(stiffness);
  const zeta = damping / (2 * w0);
  if (zeta < 1) {
    const wd = w0 * Math.sqrt(1 - zeta * zeta);
    return 1 - Math.exp(-zeta * w0 * t) * (Math.cos(wd * t) + ((zeta * w0) / wd) * Math.sin(wd * t));
  }
  if (zeta === 1) return 1 - Math.exp(-w0 * t) * (1 + w0 * t);
  const r1 = -w0 * (zeta - Math.sqrt(zeta * zeta - 1));
  const r2 = -w0 * (zeta + Math.sqrt(zeta * zeta - 1));
  return 1 - (r2 * Math.exp(r1 * t) - r1 * Math.exp(r2 * t)) / (r2 - r1);
}

/** Time (ms, rounded up to 10) after which the spring stays within 1 % of rest (the tail past that is not visible). */
export function settleMs(spring) {
  let last = 0;
  for (let t = 0; t <= 3; t += 0.001) if (Math.abs(springAt(spring, t) - 1) > 0.01) last = t;
  return Math.ceil((last * 1000) / 10) * 10;
}

/** The spring as a CSS linear() easing, 32 samples over its settle time. */
export function springEasing(spring) {
  const ms = settleMs(spring);
  const points = [];
  for (let i = 0; i <= 32; i++) points.push(+(i === 32 ? 1 : springAt(spring, (ms / 1000) * (i / 32))).toFixed(4));
  return `linear(${points.join(", ")})`;
}

export function motionCss() {
  const springs = Object.entries(SPRINGS)
    .map(([name, s]) => `  --spring-${name}: ${springEasing(s)};\n  --spring-${name}-ms: ${settleMs(s)}ms;`)
    .join("\n");
  return `/* Generated by scripts/build-springs.mjs; edit the script, not this file. Motion tokens (motion-bookmarks.pdf). */
:root {
${springs}
  /* One ease-out for everything that isn't a spring (DESIGN.md: ease-out to enter, never ease-in on UI). */
  --ease-out: cubic-bezier(0.23, 1, 0.32, 1);
  --dur-fast: 150ms; /* presses, hovers, small state changes */
  --dur-base: 220ms; /* things that enter: tooltips, rows, toasts */
  --dur-page: 300ms; /* panels, sheets, page changes */
  --stagger: 45ms; /* between items entering one after another */
}

/* A number changing: the old value leaves 0.6 em one way while the new one arrives from the other (RollingNumber). */
@keyframes roll-in-up { from { transform: translateY(0.6em); opacity: 0; } }
@keyframes roll-in-down { from { transform: translateY(-0.6em); opacity: 0; } }
@keyframes roll-out-up { to { transform: translateY(-0.6em); opacity: 0; } }
@keyframes roll-out-down { to { transform: translateY(0.6em); opacity: 0; } }
/* A check mark (an icon mask) drawing in from the left. */
@keyframes check-in { from { clip-path: inset(0 100% 0 0); } }
/* Something that didn't work: 4 px either way, twice (Loading to success's failure). */
@keyframes shake { 20%, 60% { transform: translateX(-4px); } 40%, 80% { transform: translateX(4px); } }
/* Something entering: a short fade and an 8 px rise. */
@keyframes fade-rise { from { transform: translateY(8px); opacity: 0; } }
/* Reduced motion: the same changes as fades only. */
@keyframes fade-in { from { opacity: 0; } }
@keyframes fade-out { to { opacity: 0; } }
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = new URL("../src/styles/motion.css", import.meta.url);
  writeFileSync(out, motionCss());
  console.log("build-springs: wrote src/styles/motion.css");
}
